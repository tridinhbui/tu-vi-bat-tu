"""Report composer (docs/REASONING-ENGINE-DESIGN.md §6): conclusions + palace dossiers + period layer + Bát Tự assessment -> chapters with
the six fixed sections

  nhan_dinh_tong_quan   Nhận định tổng quan        what the chapter is about on this chart, in one or two sentences
  co_so_luan_giai       Cơ sở luận giải            the chart facts and the method (sources) the reading stands on
  yeu_to_ho_tro         Yếu tố hỗ trợ              favourable conclusions, each once, with its facts and sources
  han_che_mau_thuan     Điểm hạn chế và mâu thuẫn  limiting conclusions and how they relate to the favourable ones
  luan_giai_tong_hop    Luận giải tổng hợp         the conditional synthesis: what holds, under which conditions; no score, no averaging
  dieu_kien_gioi_han    Điều kiện và giới hạn      qualifiers, open questions, school differences, scope guards

Every sentence is assembled from structured data; nothing is generated by a language model. The disclaimer that readings are traditional
symbols, not predictions, is said ONCE in the report header, not per chapter.
"""
