"""Dignity coverage report and validator for engine/data/dignity_kb.json.

    .venv/bin/python tools/dignity_coverage.py            # writes docs/STAR-DIGNITY-COVERAGE.md
    .venv/bin/python tools/dignity_coverage.py --check    # validates only; exit 1 on any problem

1. Reachability: an exhaustive sweep (60 years = every can-chi year, every day, every hour branch, gender alternating so both ring
   directions occur each year) records which branches each star can actually occupy. A cell no chart can produce is '—'.
2. Every star the engine places must be in the knowledge base, with a status in every branch for every school.
3. Every VERIFIED cell must carry a book locator; no CONFLICT/UNVERIFIED/NOT_APPLICABLE cell may carry a level.
4. The coverage matrix (M V Đ L B H = verified level, ? = conflict, · = unverified, × = not applicable, — = unreachable) and the list of
   unresolved reachable cells are written to docs/STAR-DIGNITY-COVERAGE.md.
"""
from __future__ import annotations

import datetime
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "engine"))
from tvbt import tuvi  # noqa: E402
from tvbt.calendar_core import BirthInput, normalize  # noqa: E402

KB = json.loads((ROOT / "engine" / "data" / "dignity_kb.json").read_text("utf-8"))
BR = KB["branches"]
AB = {"miếu": "M", "vượng": "V", "đắc": "Đ", "lợi": "L", "bình": "B", "hãm": "H"}
OUT = ROOT / "docs" / "STAR-DIGNITY-COVERAGE.md"


def reachability() -> dict[str, set[str]]:
    seen: dict[str, set[str]] = defaultdict(set)
    d, end, i = datetime.date(1984, 2, 2), datetime.date(2044, 1, 30), 0
    while d <= end:
        for h in range(0, 24, 2):
            c = tuvi.compute(normalize(BirthInput(d.year, d.month, d.day, h, 10, "Asia/Ho_Chi_Minh", ("male", "female")[i % 2])))
            for s in c.stars:
                seen[s.name].add(BR[s.branch])
            for hoa, v in c.tu_hoa.items():
                if v["branch"] is not None:
                    seen[hoa].add(BR[v["branch"]])
        d += datetime.timedelta(days=1)
        i += 1
    return seen


def symbol(r: dict) -> str:
    return {"VERIFIED": lambda: AB[r["value"]] + ("*" if r.get("legacy") else ""), "CONFLICT": lambda: "?",
            "UNVERIFIED": lambda: "·", "NOT_APPLICABLE": lambda: "×"}[r["status"]]()


def validate(reach: dict[str, set[str]]) -> list[str]:
    errs = []
    for star in reach:
        if star not in KB["stars"]:
            errs.append(f"placed by the engine but missing from the knowledge base: {star}")
    for school, rows in KB["resolved"].items():
        for star, row in rows.items():
            if set(row) != set(BR):
                errs.append(f"{school}/{star}: not every branch has a status")
            for b, r in row.items():
                if r["status"] == "VERIFIED" and not (r.get("locator") and r.get("value") in AB):
                    errs.append(f"{school}/{star}/{b}: VERIFIED without level or locator")
                if r["status"] != "VERIFIED" and "value" in r:
                    errs.append(f"{school}/{star}/{b}: {r['status']} carries a level")
    return errs


def report(reach: dict[str, set[str]]) -> str:
    L = ["# Star dignity coverage (generated)", "",
         "Generated by `tools/dignity_coverage.py` from `engine/data/dignity_kb.json` and an exhaustive placement sweep "
         "(1984-02-02 … 2044-01-30, every day, every hour branch). Do not edit by hand.", "",
         "Legend: **M V Đ L B H** verified level (`*` = legacy lợi→đắc reading, flagged) · **?** the book prints two readings "
         "(CONFLICT) · **·** no classification found (UNVERIFIED) · **×** a book says brightness does not apply · **—** the star "
         "can never stand in that branch.", ""]
    for school, meta in KB["schools"].items():
        rows = KB["resolved"][school]
        tally, stars_by = Counter(), Counter()
        for star, row in rows.items():
            cells = [row[b] for b in BR if b in reach.get(star, set())]
            for r in cells:
                tally[r["status"]] += 1
            st = {r["status"] for r in cells}
            stars_by["all reachable cells verified" if st == {"VERIFIED"} else "not applicable" if st == {"NOT_APPLICABLE"}
                     else "no classification anywhere" if st <= {"UNVERIFIED"} else "partly classified"] += 1
        total = sum(tally.values())
        L += [f"## {meta['title']} (`{school}`)", "",
              f"Reachable cells: {total} · VERIFIED {tally['VERIFIED']} ({100 * tally['VERIFIED'] / total:.1f}%) · CONFLICT "
              f"{tally['CONFLICT']} · UNVERIFIED {tally['UNVERIFIED']} · NOT_APPLICABLE {tally['NOT_APPLICABLE']}", "",
              "Stars: " + " · ".join(f"{k} {v}" for k, v in sorted(stars_by.items())), "",
              "| Sao | Nhóm | " + " | ".join(BR) + " |", "|---|---|" + "---|" * 12]
        for star, m in KB["stars"].items():
            row = rows[star]
            L.append(f"| {star} | {m['group']} | " + " | ".join(symbol(row[b]) if b in reach.get(star, set()) else "—" for b in BR) + " |")
        L.append("")
    L += ["## Unresolved reachable cells of stars that HAVE a table (default school)", "",
          "Stars with no table at all are listed once in the matrix; this list is the research backlog where a book does tabulate "
          "the star but not this branch, or prints two readings.", "", "| Sao | Cung | Status | Why |", "|---|---|---|---|"]
    rows = KB["resolved"][KB["default_school"]]
    for star, row in rows.items():
        if not any(r["status"] == "VERIFIED" for r in row.values()):
            continue
        for b in BR:
            r = row[b]
            if b in reach.get(star, set()) and r["status"] in ("CONFLICT", "UNVERIFIED"):
                why = r.get("reason") or " / ".join(f"{a['term']} ({a['locator']})" for a in r.get("alternatives", []))
                L.append(f"| {star} | {b} | {r['status']} | {why} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    reach = reachability()
    errs = validate(reach)
    for e in errs:
        print("ERROR", e)
    if "--check" not in sys.argv:
        OUT.write_text(report(reach), "utf-8")
        print("wrote", OUT)
    sys.exit(1 if errs else 0)
