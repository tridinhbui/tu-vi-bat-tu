"""DEEP-3 review record and report table, from the mined entries and the built packs:
    engine/data/kg/rule_review_2026-10-24.json   every new rule (page, quote, how checked) and every mined entry not made a rule (reason / duplicate)
    docs/audit/DEEP-3-mining-tuvi.md             the table between <!-- SKIPPED --> markers
Run after tools/build_deep3_tuvi_pack.py:  .venv/bin/python tools/mining/deep3/report.py"""
import glob
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
D = os.path.join(ROOT, "engine", "data")
M = {}
for f in sorted(glob.glob(os.path.join(D, "kg", "mined", "deep3_*.json"))):
    for e in json.load(open(f, encoding="utf-8"))["entries"]:
        M[e["id"]] = e
Q = json.load(open(os.path.join(D, "quotes_deep3_tuvi.json"), encoding="utf-8"))
P = {}
for n in ("pack_toan_thu_ca.json", "pack_khao_luan_cach.json", "pack_toan_thu_han_van.json"):
    for r in json.load(open(os.path.join(D, n), encoding="utf-8"))["rules"]:
        P[r["id"]] = n


def cite(e):
    if e["book"].startswith("WEB:"):
        return f"TTH {e['book'].rsplit('_', 1)[1]} {e['page']}"
    if e["book"].startswith("SCAN:"):
        return f"TL scan p.{e['page']}"
    return f"{e['book']} p.{e['page']}"


def how(e):
    if e["book"].startswith("WEB:"):
        return "quote_on_page on the saved zh.wikisource snapshot (section)"
    if e["book"] == "TH":
        return "page image read; the quote is a contiguous fragment of the text layer"
    return "text layer in reading order; quote_on_page"


rules, seen = [], set()
for x in Q["quotes"]:
    if x["rule"] in seen:
        continue
    seen.add(x["rule"])
    e = M[x["mined"]]
    rules.append({"id": x["rule"], "pack": P[x["rule"]], "page": cite(e), "status": "verified", "quote": e["quote"], "mined": e["id"],
                  "note": (e.get("notes") or "")[:300], "checked_by": how(e) + ", 2026-10-24"})
not_rules = [{"mined": k, "page": cite(M[k]), "status": "skipped", "reason": v} for k, v in Q["skipped"].items()] + \
            [{"mined": k, "page": cite(M[k]), "status": "duplicate", "of": v} for k, v in Q["duplicates"].items()]
json.dump({"version": "2026-10-24",
           "note": "DEEP-3 Tử Vi mining (plan pasted-content-id-885b … radiant-donut, Workstream B): every new rule with its page and quote, and every mined "
                   "entry not made a rule with the reason (skipped) or the rule / cách it repeats (duplicate). verified = the quote passes tools/book_text.py "
                   "quote_on_page on its page (PDF), section (紫微斗數全書 snapshot) or transcribed scan page, and the condition is no broader than the page. "
                   "Report: docs/audit/DEEP-3-mining-tuvi.md. Generated by tools/mining/deep3/report.py.",
           "rules": rules, "not_rules": not_rules},
          open(os.path.join(D, "kg", "rule_review_2026-10-24.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

esc = lambda t: str(t).replace("|", "/")
lines = ["| mined id | page | line (quote) | reason |", "|---|---|---|---|"]
lines += [f"| `{k}` | {cite(e)} | {esc(e['quote'])} | {esc(e['skip'])} |" for k, e in M.items() if e.get("skip")]
lines += ["", "**Duplicates** (the line is already a verified rule or cách; not made twice):", "", "| mined id | page | already read by |", "|---|---|---|"]
lines += [f"| `{k}` | {cite(e)} | `{e['duplicate_of']}` |" for k, e in M.items() if e.get("duplicate_of")]
doc = os.path.join(ROOT, "docs", "audit", "DEEP-3-mining-tuvi.md")
s = open(doc, encoding="utf-8").read()
s = re.sub(r"<!-- SKIPPED -->.*<!-- /SKIPPED -->", lambda _: "<!-- SKIPPED -->\n" + "\n".join(lines) + "\n<!-- /SKIPPED -->", s, flags=re.S)
open(doc, "w", encoding="utf-8").write(s)
print(len(rules), "rules;", len(not_rules), "not rules")
