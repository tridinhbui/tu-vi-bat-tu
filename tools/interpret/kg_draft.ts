// Drafts the knowledge-graph links (prose plan P1 for Mệnh, P5 for every palace). Run after a rule-pack or concept change, then rebuild:
//   node tools/interpret/build.ts && node tools/interpret/kg_draft.ts && node tools/interpret/build.ts
// 1. rule_concepts.json: every Tử Vi rule -> concept assertions. Hand links in
//    rule_concepts.manual.json win; the rest come ONCE from the cue lexicon over the rule's own paraphrase (src 'auto'), so the runtime
//    never matches text. Every entry is review 'draft' until a reviewer approves it.
// 2. relations.json: the book-stated relations (relations.manual.json, basis 'sach') plus one entry for every pair of opposed assertions
//    that co-fires on one palace on the 1,000-chart corpus, typed from how their evidence nests (basis 'he_thong', a labelled convention):
//    narrower evidence -> 'narrows'; identical evidence -> 'unresolved' (books disagree on the same facts); otherwise 'both_hold'.
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { join } from 'node:path';
import { run } from '../../src/interpret/engine.ts';
import { Lexicon, readingOf, splitReading } from '../../src/interpret/semantic.ts';
import { lift, type RuleConcept } from '../../src/interpret/kg/lift.ts';
import { opposed, type KgRelation } from '../../src/interpret/kg/resolve.ts';
import { nesting } from '../../src/interpret/kg/atoms.ts';
import type { Knowledge } from '../../src/interpret/types.ts';

const ROOT = join(import.meta.dirname, '..', '..'), KG = join(ROOT, 'engine', 'data', 'kg');
const read = (p: string) => JSON.parse(readFileSync(p, 'utf8'));
const K0: Knowledge = read(join(ROOT, 'src', 'interpret', 'generated', 'knowledge.json'));
const K: Knowledge = K0;                                     // concepts = cue lexicon + KG-only concepts (build.ts merges them)
const cmap = new Map(K.concepts.concepts.map(c => [c.id, c]));

// ---- 1. rule -> concept ----
const manual: Record<string, Omit<RuleConcept, 'src' | 'review'>> = read(join(KG, 'rule_concepts.manual.json')).entries;
const lex = new Lexicon(K);
// every Tử Vi rule (prose plan P5: all twelve palaces; Mệnh came first)
const inScope = (r: Knowledge['rules'][number]) => r.system === 'tu_vi';
const entries: Record<string, RuleConcept> = {};
const unknown: string[] = [];
for (const r of K.rules.filter(inScope).sort((a, b) => a.id < b.id ? -1 : 1)) {
  const c = r.consequences.find(x => x.kind === 'finding' && x.claim);
  if (!c) continue;
  if (manual[r.id]) { entries[r.id] = { ...manual[r.id], src: 'manual', review: 'draft' }; continue; }
  const { core } = splitReading(readingOf(r, K.claims, c.claim!, c.effect ?? 'support'));
  const low = core.toLowerCase();
  const strength = /có thể/.test(low) ? 'potential' as const : /\b(nếu|khi|mới)\b/.test(low) ? 'condition' as const : undefined;
  const asserts = lex.match(core).map(m => ({ concept: m.id, stance: (c.effect === 'limit' && cmap.get(m.id)?.pol === '+' ? 'weakens' : 'affirms') as 'affirms' | 'weakens', ...(strength ? { strength } : {}) }));
  entries[r.id] = { asserts, src: 'auto', review: 'draft' };
}
for (const [id, e] of Object.entries(manual)) {
  if (!K.rules.some(r => r.id === id)) throw new Error(`manual link names an unknown rule: ${id}`);
  for (const a of e.asserts) if (!cmap.has(a.concept)) throw new Error(`${id}: unknown concept ${a.concept}`);
}
for (const [id, e] of Object.entries(entries)) if (!e.asserts.length && !e.kind) unknown.push(id);
writeFileSync(join(KG, 'rule_concepts.json'), JSON.stringify({
  version: '0.1.0', note: 'Generated by tools/interpret/kg_draft.ts from rule_concepts.manual.json (src manual) and the cue lexicon (src auto); edit the manual file, not this one. Every entry is a draft until reviewed.',
  entries }, null, 1) + '\n');

// ---- 2. relations ----
const manualRels: KgRelation[] = read(join(KG, 'relations.manual.json')).relations.map((r: KgRelation) => ({ ...r, review: r.review ?? 'draft' }));
for (const r of manualRels) for (const id of [r.from, ...r.to]) if (!K.rules.some(x => x.id === id)) throw new Error(`${r.id}: unknown rule ${id}`);
const declared = new Set(manualRels.flatMap(r => r.to.flatMap(t => [`${r.from}|${t}`, `${t}|${r.from}`])));
const KK: Knowledge = { ...K, kg: { ...K.kg!, ruleConcepts: entries, relations: manualRels } };
const corpus = JSON.parse(gunzipSync(readFileSync(join(ROOT, 'src', 'interpret', 'test', 'fixtures', 'corpus1000.json.gz'))).toString('utf8'));
const pairs = new Map<string, { a: string; b: string; concept: string; nest: Record<string, number>; charts: number }>();
let pairCharts = 0, declaredHits = 0;
for (const c of corpus) {
  const res = run(K.rules, K.sources, c.facts.base);
  const { assertions } = lift(res.findings, KK, c.facts.base);
  const at = assertions;
  const seen = new Set<string>();
  for (let i = 0; i < at.length; i++) for (let j = i + 1; j < at.length; j++) {
    const x = at[i], y = at[j];
    // opposed readings of the same subject (one palace, or the chart); chart-level readings meet the Mệnh palace's
    const sameSubject = x.subject === y.subject || (x.subject === 'chart' && y.subject === 'palace:Mệnh') || (y.subject === 'chart' && x.subject === 'palace:Mệnh');
    if (!sameSubject || x.ruleId === y.ruleId || !opposed(x, y, cmap)) continue;
    const [a, b] = x.ruleId < y.ruleId ? [x, y] : [y, x], key = `${a.ruleId}|${b.ruleId}`;
    if (seen.has(key)) continue;
    seen.add(key);
    pairCharts++;
    if (declared.has(key)) { declaredHits++; continue; }
    const p = pairs.get(key) ?? { a: a.ruleId, b: b.ruleId, concept: a.concept, nest: {}, charts: 0 };
    // an assertion resting only on year/sex facts has no chart evidence to nest: never 'narrower' or 'same' by vacuity
    const n = a.sig.size && b.sig.size ? nesting(a.sig, b.sig) : 'disjoint';
    p.nest[n] = (p.nest[n] ?? 0) + 1;
    p.charts++;
    pairs.set(key, p);
  }
}
const auto: KgRelation[] = [...pairs.values()].sort((x, y) => y.charts - x.charts || (x.a + x.b < y.a + y.b ? -1 : 1)).map(p => {
  const kinds = Object.keys(p.nest);
  const base = { basis: 'he_thong' as const, review: 'draft' as const, charts: p.charts };
  if (kinds.length === 1 && kinds[0] === 'narrower') return { id: `AUTO_${p.a}__${p.b}`, type: 'narrows' as const, from: p.a, to: [p.b], effect: 'none' as const, ...base, note: `cụ thể hơn về ${p.concept}` };
  if (kinds.length === 1 && kinds[0] === 'broader') return { id: `AUTO_${p.b}__${p.a}`, type: 'narrows' as const, from: p.b, to: [p.a], effect: 'none' as const, ...base, note: `cụ thể hơn về ${p.concept}` };
  if (kinds.length === 1 && kinds[0] === 'same') return { id: `AUTO_${p.a}__${p.b}`, type: 'unresolved' as const, from: p.a, to: [p.b], effect: 'none' as const, ...base, note: `cùng dữ kiện, hai chiều về ${p.concept}` };
  return { id: `AUTO_${p.a}__${p.b}`, type: 'both_hold' as const, from: p.a, to: [p.b], effect: 'none' as const, ...base, note: `${p.concept}; nesting ${JSON.stringify(p.nest)}` };
});
writeFileSync(join(KG, 'relations.json'), JSON.stringify({
  version: '0.1.0', note: 'Generated by tools/interpret/kg_draft.ts: relations.manual.json (basis sach) + one draft entry per opposed rule pair that co-fires on one palace on the 1,000-chart corpus (basis he_thong). Edit the manual file.',
  relations: [...manualRels, ...auto] }, null, 1) + '\n');

const by = (xs: KgRelation[]) => xs.reduce((o, r) => (o[r.type] = (o[r.type] ?? 0) + 1, o), {} as Record<string, number>);
const n = Object.keys(entries).length, nAuto = Object.values(entries).filter(e => e.src === 'auto').length;
console.log(`rule_concepts: ${n} Tử Vi rules, ${n - nAuto} manual, ${nAuto} auto, ${unknown.length} without a concept: ${unknown.join(', ') || '-'}`);
console.log(`relations: ${manualRels.length} sach, ${auto.length} he_thong ${JSON.stringify(by(auto))}; opposed pair-occurrences on corpus ${pairCharts}, of which on a sach relation ${declaredHits}`);
